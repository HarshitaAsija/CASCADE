"""Generate serialized TypeScript contracts from the Pydantic source of truth."""
from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'backend'))
from app import schemas  # noqa: E402


def ts_type(schema: dict) -> str:
    if '$ref' in schema:
        return schema['$ref'].rsplit('/', 1)[-1]
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(ts_type(value) for value in schema['anyOf'])
    kind = schema.get('type')
    if kind == 'array':
        if 'prefixItems' in schema:
            return '[' + ', '.join(ts_type(item) for item in schema['prefixItems']) + ']'
        return 'Array<' + ts_type(schema.get('items', {})) + '>'
    if kind == 'object':
        additional = schema.get('additionalProperties', {})
        return 'Record<string, ' + (ts_type(additional) if isinstance(additional, dict) else 'unknown') + '>'
    return {'integer': 'number', 'number': 'number', 'string': 'string',
            'boolean': 'boolean', 'null': 'null'}.get(kind, 'unknown')


def generate() -> str:
    blocks = [
        '// Generated by scripts/generate_types.py. Do not edit by hand.',
        '// Serialized fields are required; request provenance defaults to simulated when omitted.',
        'export type Provenance = "real" | "estimated" | "simulated";',
        'export type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };',
    ]
    for name, model in vars(schemas).items():
        if not isinstance(model, type) or not issubclass(model, schemas.Contract):
            continue
        if name in {'Contract', 'ProvenancedContract'}:
            continue
        properties = model.model_json_schema(mode='serialization')['properties']
        fields = [f'  {key}: ' + ('Provenance' if key == 'provenance' else ts_type(value)) + ';'
                  for key, value in properties.items()]
        blocks.append('export interface ' + name + ' {\n' + '\n'.join(fields) + '\n}')
    return '\n\n'.join(blocks) + '\n'


if __name__ == '__main__':
    output = ROOT / 'frontend/src/types.ts'
    content = generate()
    if '--check' in sys.argv:
        if not output.exists() or output.read_text(encoding='utf-8') != content:
            raise SystemExit('TypeScript contracts are stale. Run scripts/generate_types.py.')
        print('TypeScript contracts match Pydantic schemas.')
    else:
        output.write_text(content, encoding='utf-8')
        print('Generated frontend/src/types.ts')
